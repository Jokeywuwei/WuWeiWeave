export type TranslationKey = keyof typeof translations.zh;

const I18nContext = createContext<I18nContextValue | undefined>(undefined);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(() => {
    const saved = window.localStorage.getItem("wuweiweave.language");
    return saved === "en" || saved === "zh" ? saved : "zh";
  });

  const value = useMemo<I18nContextValue>(() => {
    const setLanguage = (nextLanguage: Language) => {
      window.localStorage.setItem("wuweiweave.language", nextLanguage);
      setLanguageState(nextLanguage);
    };

    return {
      language,
      setLanguage,
      t: (key) => translations[language][key]
    };
  }, [language]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const value = useContext(I18nContext);
  if (!value) {
    throw new Error("useI18n must be used within I18nProvider");
  }
  return value;
}

export function translateStatus(status: string, t: (key: TranslationKey) => string) {
  const key = `status.${status}` as TranslationKey;
  return key in translations.zh ? t(key) : status;
}
